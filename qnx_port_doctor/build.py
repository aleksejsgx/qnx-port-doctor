"""Cross-build helpers wrapping QNX SDP (qcc, CMake toolchain, autotools)."""
import os
import shlex
import shutil
import subprocess

# arch -> (qcc variant, cmake processor, GNU host triple)
ARCH = {
    "x86_64": ("gcc_ntox86_64", "x86_64", "x86_64-pc-nto-qnx8.0.0"),
    "aarch64le": ("gcc_ntoaarch64le", "aarch64", "aarch64-unknown-nto-qnx8.0.0"),
}

# Libraries that QNX keeps outside libc; linked when the code needs them.
QNX_LIBS = ["-lsocket", "-lregex", "-lm"]

TOOLCHAIN = """# Generated by qnx-port-doctor
set(CMAKE_SYSTEM_NAME QNX)
set(CMAKE_SYSTEM_PROCESSOR {proc})
set(QNX_HOST $ENV{{QNX_HOST}})
set(QNX_TARGET $ENV{{QNX_TARGET}})
set(CMAKE_C_COMPILER ${{QNX_HOST}}/usr/bin/qcc)
set(CMAKE_CXX_COMPILER ${{QNX_HOST}}/usr/bin/q++)
set(CMAKE_C_COMPILER_TARGET {variant})
set(CMAKE_CXX_COMPILER_TARGET {variant}_cxx)
set(CMAKE_C_FLAGS_INIT "-V{variant}")
set(CMAKE_CXX_FLAGS_INIT "-V{variant}_cxx")
set(CMAKE_SYSROOT ${{QNX_TARGET}})
set(CMAKE_FIND_ROOT_PATH ${{QNX_TARGET}} ${{QNX_TARGET}}/{arch})
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
"""


def compat_header():
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "qnx_compat.h")


def check_env():
    missing = [v for v in ("QNX_HOST", "QNX_TARGET") if not os.environ.get(v)]
    if missing or not shutil.which("qcc"):
        raise SystemExit("QNX SDP environment not set: run `source <sdp>/qnxsdp-env.sh` first")


def write_toolchain(path, arch):
    variant, proc, _ = ARCH[arch]
    with open(path, "w") as f:
        f.write(TOOLCHAIN.format(proc=proc, variant=variant, arch=arch))
    return path


def autotools_plan(src, arch="x86_64", prefix=None, configure_args=(), extra_libs=(), compat=True,
                   jobs=8, make_targets=()):
    """Return (env, [commands]) for an out-of-the-box autotools cross build."""
    variant, _, host = ARCH[arch]
    cppflags = []
    ldflags = []
    if prefix:
        cppflags.append(f"-I{prefix}/include")
        ldflags.append(f"-L{prefix}/lib")
    if compat:
        cppflags += ["-include", compat_header()]
    libs = " ".join(QNX_LIBS + list(extra_libs))
    env = {
        "CC": f"qcc -V{variant}", "CXX": f"q++ -V{variant}_cxx",
        "AR": f"{host}-ar", "RANLIB": f"{host}-ranlib",
        "CPPFLAGS": " ".join(cppflags), "LDFLAGS": " ".join(ldflags), "LIBS": libs,
    }
    if prefix:
        env["PKG_CONFIG_LIBDIR"] = f"{prefix}/lib/pkgconfig"
        env["PKG_CONFIG_PATH"] = ""
    cmds = []
    if not os.path.exists(os.path.join(src, "configure")):
        cmds.append(["autoreconf", "-fi"])
    conf = ["./configure", f"--host={host}"]
    if prefix:
        conf.append(f"--prefix={prefix}")
    cmds.append(conf + list(configure_args))
    cmds.append(["make", f"-j{jobs}", *make_targets])
    return env, cmds


def build(src, arch="x86_64", out="build-qnx", dry_run=False, autotools=False, prefix=None,
          configure_args=(), extra_libs=(), compat=True, jobs=8, extra_env=None):
    variant, _, _ = ARCH[arch]
    env, cwd = {}, None
    if autotools:
        env, cmds = autotools_plan(src, arch, prefix, configure_args, extra_libs, compat, jobs)
        env.update(extra_env or {})
        cwd = src
    elif os.path.isfile(src):
        cmds = [["qcc", f"-V{variant}", src, "-o", os.path.join(out, os.path.splitext(os.path.basename(src))[0])]]
    elif os.path.exists(os.path.join(src, "CMakeLists.txt")):
        tc = os.path.abspath(os.path.join(out, f"qnx-{arch}.cmake"))
        cmds = [["cmake", "-S", src, "-B", out, f"-DCMAKE_TOOLCHAIN_FILE={tc}"], ["cmake", "--build", out, "-j"]]
    else:
        cmds = [["make", "-C", src, f"CC=qcc -V{variant}", f"CXX=q++ -V{variant}_cxx"]]
    for k, v in env.items():
        print(f"+ export {k}={shlex.quote(v)}", flush=True)
    for c in cmds:
        print("+", " ".join(shlex.quote(x) for x in c), flush=True)
    if dry_run:
        return 0
    check_env()
    if not autotools:
        os.makedirs(out, exist_ok=True)
        if os.path.isdir(src) and os.path.exists(os.path.join(src, "CMakeLists.txt")):
            write_toolchain(os.path.join(out, f"qnx-{arch}.cmake"), arch)
    full_env = dict(os.environ, **env)
    for c in cmds:
        r = subprocess.run(c, cwd=cwd, env=full_env)
        if r.returncode:
            return r.returncode
    return 0
