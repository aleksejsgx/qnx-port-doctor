"""Cross-build helpers wrapping QNX SDP (qcc / CMake toolchain)."""
import os
import shutil
import subprocess

ARCH = {"x86_64": ("gcc_ntox86_64", "x86_64"), "aarch64le": ("gcc_ntoaarch64le", "aarch64")}

TOOLCHAIN = """# Generated by qnx-port-doctor
set(CMAKE_SYSTEM_NAME QNX)
set(CMAKE_SYSTEM_PROCESSOR {proc})
set(QNX_HOST $ENV{{QNX_HOST}})
set(QNX_TARGET $ENV{{QNX_TARGET}})
set(CMAKE_C_COMPILER ${{QNX_HOST}}/usr/bin/qcc)
set(CMAKE_CXX_COMPILER ${{QNX_HOST}}/usr/bin/q++)
set(CMAKE_C_COMPILER_TARGET {variant})
set(CMAKE_CXX_COMPILER_TARGET {variant}_cxx)
set(CMAKE_C_FLAGS_INIT "-V{variant}")
set(CMAKE_CXX_FLAGS_INIT "-V{variant}_cxx")
set(CMAKE_SYSROOT ${{QNX_TARGET}})
set(CMAKE_FIND_ROOT_PATH ${{QNX_TARGET}} ${{QNX_TARGET}}/{arch})
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
"""


def check_env():
    missing = [v for v in ("QNX_HOST", "QNX_TARGET") if not os.environ.get(v)]
    if missing or not shutil.which("qcc"):
        raise SystemExit("QNX SDP environment not set: run `source <sdp>/qnxsdp-env.sh` first")


def write_toolchain(path, arch):
    variant, proc = ARCH[arch]
    with open(path, "w") as f:
        f.write(TOOLCHAIN.format(proc=proc, variant=variant, arch=arch))
    return path


def build(src, arch="x86_64", out="build-qnx", dry_run=False):
    variant, _ = ARCH[arch]
    if os.path.isfile(src):
        cmd = [["qcc", f"-V{variant}", src, "-o", os.path.join(out, os.path.splitext(os.path.basename(src))[0])]]
    elif os.path.exists(os.path.join(src, "CMakeLists.txt")):
        tc = os.path.abspath(os.path.join(out, f"qnx-{arch}.cmake"))
        cmd = [["cmake", "-S", src, "-B", out, f"-DCMAKE_TOOLCHAIN_FILE={tc}"], ["cmake", "--build", out, "-j"]]
    else:
        env = f"CC=qcc -V{variant}"
        cmd = [["make", "-C", src, f"CC=qcc -V{variant}", f"CXX=q++ -V{variant}_cxx"]]
    for c in cmd:
        print("+", " ".join(c))
    if dry_run:
        return 0
    check_env()
    os.makedirs(out, exist_ok=True)
    if os.path.isdir(src) and os.path.exists(os.path.join(src, "CMakeLists.txt")):
        write_toolchain(os.path.join(out, f"qnx-{arch}.cmake"), arch)
    for c in cmd:
        r = subprocess.run(c)
        if r.returncode:
            return r.returncode
    return 0
